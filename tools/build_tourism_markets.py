"""Rebuild the traditional-market Atlas supplement from the distributed OSM snapshots.

Run python tools/build_tourism_markets.py with the dependencies of build_vn_tourism.py.
The tourism references identify the visitor destinations. Their pins use the same
OSM objects as vn-amenities and their starts use the Atlas's drivable-road projection.
"""
import gzip
import json
from pathlib import Path
import unicodedata

from build_vn_tourism import REGIONS, road_approaches


DIST = Path(__file__).resolve().parents[1] / "dist"
# Where two mapped halls or a hall and a POI represent the same market, keep one stop.
MARKETS = {
    "w712584152": ("Lai Châu", "San Thàng", "https://vietnamtourism.gov.vn/printer/66209?type=1"),
    "w234956885": ("Lào Cai", "Bắc Hà", "https://csdl.vietnamtourism.gov.vn/dest/?item=141"),
    "n4811351954": ("Lào Cai", "Sa Pa", "https://csdl.vietnamtourism.gov.vn/shop/?item=504"),
    "w1212230635": ("Hà Nội", "Đồng Xuân", "https://vietnam.travel/things-to-do/shopping-hanoi-markets-and-malls/"),
    "w930229621": ("Hà Nội", "Hồng Hà", "https://vietnam.travel/things-to-do/shopping-hanoi-markets-and-malls/"),
    "w87200797": ("Quảng Trị", "Đồng Hới", "https://vietnamtourism.gov.vn/printer/46238?type=1"),
    "w204885903": ("Đà Nẵng", "Đà Nẵng", "https://csdl.vietnamtourism.gov.vn/shop/?item=57"),
    "r4119185": ("Lâm Đồng", "Đà Lạt", "https://csdl.vietnamtourism.gov.vn/dest/?item=126"),
    "w39598471": ("Hồ Chí Minh", "Tân Định", "https://hello.hochiminhcity.gov.vn/vi/discover/cho-va-cho-dem-sai-gon"),
    "w116866865": ("An Giang", "Châu Đốc", "https://chaudoc.angiang.gov.vn/thong-tin-khai-quat-ve-phuong-chau-doc"),
    "w1328291798": ("An Giang", "Dương Đông", "https://dulich.phuquoc.gov.vn/vi/detailevents/?id=event_382&t=cho-duong-dong-phu-quoc"),
}


def build():
    folder = DIST / "vn-amenities"
    manifest = json.loads((folder / "index.json").read_text(encoding="utf8"))
    pins = {}
    for tile in manifest["tiles"]:
        with gzip.open(folder / (tile + ".gz"), "rt", encoding="utf8") as src:
            for ref, kind, name, x, y in json.load(src):
                if ref in MARKETS and kind == "market" and name:
                    pins[ref] = (unicodedata.normalize("NFC", name), x / manifest["scale"], y / manifest["scale"])
    missing = MARKETS.keys() - pins.keys()
    if missing:
        raise ValueError(f"Market missing from the mapped amenities: {sorted(missing)}")

    # road_approaches expects the intermediate records used by the national Atlas.
    roads = DIST / "vn-roads"
    index = json.loads((roads / "index.json").read_text(encoding="utf8"))
    entries = []
    for ref, (province, _, _) in MARKETS.items():
        name, lon, lat = pins[ref]
        entries.append((province, 0, ref, name, "Chợ truyền thống", lon, lat, ""))
    starts = road_approaches(entries, roads, index)
    rows = []
    for i, (province, _, ref, name, _, lon, lat, _) in enumerate(entries):
        distance, start_lon, start_lat = starts[i]
        if distance > 200:
            raise ValueError(f"Check local road access for {ref}: {distance:.0f} metres")
        _, locality, source = MARKETS[ref]
        osm_type = {"n": "node", "w": "way", "r": "relation"}[ref[0]]
        row = [osm_type + "/" + ref[1:], name, province, locality, REGIONS[province],
               lon, lat, start_lon, start_lat, round(distance), source]
        rows.append("    " + json.dumps(row, ensure_ascii=False, separators=(",", ":")))
    script = """'use strict';
// Generated by tools/build_tourism_markets.py. Coordinates © OpenStreetMap contributors, ODbL 1.0.
(() => {
  const atlas = window.VietnamTourism;
  // Packed releases have already included these entries in their regional and national files.
  if (atlas.files) return;
  const existing = new Set(atlas.entries.map(site => site.id));
  const markets = [
""" + ",\n".join(rows) + """
  ];
  for (const [ref, name, province, locality, region, lon, lat, startLon, startLat, approachMeters, source] of markets) {
    const id = 'osm-' + ref.replace('/', '-');
    if (existing.has(id) || atlas.aliases[id]) continue;
    atlas.entries.push({id, name, province, city:province, locality, region, kind:'Chợ truyền thống',
      lon, lat, start:[startLon, startLat], approachMeters, source, map:'https://www.openstreetmap.org/' + ref});
  }
})();
"""
    (DIST / "tourism-markets.js").write_text(script, encoding="utf8", newline="\n")


if __name__ == "__main__":
    build()
